import { forwardRef } from "react";
import { Link } from "react-router";
import { CircleAlert, CircleCheck, CircleMinus, Info, type LucideIcon } from "lucide-react";
import { useStrings } from "../../lib/i18n";
import { formatNumber, formatTime } from "../../lib/format";
import type { RunSummary } from "../../lib/contracts/simulation";
import { targetPath } from "../../app/navigation";

const KIND_ICON: Record<RunSummary["assessment"][number]["kind"], LucideIcon> = {
  observation: Info,
  improved: CircleCheck,
  not_improved: CircleMinus,
  concern: CircleAlert,
};
const n = (v: number | null, d: number, unit = "") => (v === null ? "–" : `${formatNumber(v, d)}${unit ? ` ${unit}` : ""}`);

/**
 * The pilot's account of a run that has ended. Every figure and sentence comes from the
 * run's and the pilot's records (the summary's basis says so); nothing is generated by a
 * language model. Shown in AI Pilot when a run stops and in Simulation history later.
 */
export const RunSummaryView = forwardRef<HTMLHeadingElement, { summary: RunSummary; timeZone: string }>(function RunSummaryView({ summary, timeZone }, ref) {
  const s = useStrings();
  const r = s.summary;
  const t = (iso: string | null) => (iso ? formatTime(iso, timeZone) : "–");
  const id = summary.identity;
  const perf = summary.performance;
  const p = summary.pilot;
  const c = summary.corrections;
  return (
    <section className="run-summary" aria-labelledby="run-summary-title" data-summary={summary.runId}>
      <div className="sim-section__head">
        <h2 id="run-summary-title" ref={ref} tabIndex={-1}>
          {r.title(summary.runId)}
        </h2>
        <span className="tag-chip" title={r.basisTitle}>
          {r.basis}
        </span>
      </div>
      <p className="sim-muted">{r.lead(id.scenario.label, r.ended[id.endReason], `${t(id.startedAt)} to ${t(id.endedAt)}`, id.simulatedMinutes, id.plannedMinutes)}</p>

      <dl className="run-summary__figures">
        <div>
          <dt>{r.avgCop}</dt>
          <dd className="num">{n(perf.avgCop, 2)}</dd>
          <dd className="sim-muted num">{r.copSpan(n(perf.firstCop, 2), n(perf.lastCop, 2))}</dd>
        </div>
        <div>
          <dt>{r.energy}</dt>
          <dd className="num">{n(perf.energyKwh, 0, "kWh")}</dd>
          <dd className="sim-muted num">{r.avgPower(n(perf.avgPowerKw, 0, "kW"))}</dd>
        </div>
        <div>
          <dt>{r.demand}</dt>
          <dd className="num">{n(perf.avgDemandKw, 0, "kWt")}</dd>
          <dd className="sim-muted num">{r.peakDemand(n(perf.peakDemandKw, 0, "kWt"))}</dd>
        </div>
        <div>
          <dt>{r.unmet}</dt>
          <dd className="num">{n(perf.unmetKwh, 0, "kWh")}</dd>
          <dd className="sim-muted num">{r.unmetDetail(n(perf.peakUnmetKw, 0, "kWt"), perf.unmetSteps, perf.steps)}</dd>
        </div>
        <div>
          <dt>{r.issues}</dt>
          <dd className="num">{p.monitored ? p.issues : "–"}</dd>
          <dd className="sim-muted">{p.monitored ? r.issueDetail(p.investigations, p.proposals, p.declined, p.resolved) : r.notMonitored}</dd>
        </div>
        <div>
          <dt>{r.corrections}</dt>
          <dd className="num">{c.applied}</dd>
          <dd className="sim-muted">{r.correctionDetail(c.operator, c.pilot, c.rejected, c.reached, c.notReached)}</dd>
        </div>
      </dl>

      <div className="run-summary__cols">
        <section aria-labelledby="run-summary-assessment">
          <h3 id="run-summary-assessment">{r.assessment}</h3>
          <ul className="run-summary__list">
            {summary.assessment.map((a, i) => {
              const Icon = KIND_ICON[a.kind];
              return (
                <li key={i} className={`run-summary__item run-summary__item--${a.kind}`} data-assessment={a.kind}>
                  <span className="run-summary__kind">
                    <Icon size={14} aria-hidden="true" />
                    {r.kinds[a.kind]}
                  </span>
                  <span>{a.text}</span>
                </li>
              );
            })}
          </ul>
          {p.unresolved.length > 0 && (
            <>
              <h3>{r.unresolved}</h3>
              <ul className="run-summary__links">
                {p.unresolved.map((u) => (
                  <li key={u.issueId}>
                    <Link className="link" to={targetPath({ type: "simulation", runId: summary.runId, issueId: u.issueId })}>
                      {u.issueId}
                    </Link>{" "}
                    {u.title} <span className="sim-muted">({s.pilot.stages[u.stage]})</span>
                  </li>
                ))}
              </ul>
            </>
          )}
        </section>
        <section aria-labelledby="run-summary-recommendations">
          <h3 id="run-summary-recommendations">{r.recommendations}</h3>
          <ol className="run-summary__list">
            {summary.recommendations.map((x, i) => (
              <li key={i} className="run-summary__item" data-recommendation>
                <span>{x.text}</span>
                <span className="sim-muted">{r.because(x.basis)}</span>
              </li>
            ))}
          </ol>
        </section>
      </div>

      <section aria-labelledby="run-summary-timeline">
        <h3 id="run-summary-timeline">{r.timeline}</h3>
        {summary.timeline.length ? (
          <ol className="sim-timeline run-summary__timeline" aria-labelledby="run-summary-timeline" tabIndex={0}>
            {summary.timeline.map((e, i) => (
              <li key={i} className={`sim-timeline__item sim-timeline__item--${e.kind === "failure" ? "failure" : "lifecycle"}`} data-summary-kind={e.kind}>
                <time className="num" dateTime={e.at}>
                  {formatTime(e.at, timeZone)}
                </time>
                <span className="sim-timeline__kind">{r.timelineKinds[e.kind]}</span>
                <span className="sim-timeline__text">{e.text}</span>
              </li>
            ))}
          </ol>
        ) : (
          <p className="sim-empty">{r.noTimeline}</p>
        )}
      </section>
    </section>
  );
});
